/** Comprueba que una malla tenga fuente oficial completa y cursos. Devuelve la lista de problemas. */
export function validarMalla(m) {
  const errores = [];
  if (!m || typeof m !== 'object') return ['La malla no es un objeto.'];
  for (const c of ['carreraId', 'universidad', 'anio']) if (!m[c]) errores.push(`Falta «${c}».`);
  if (!m.fuente?.cita || !/^https:\/\//.test(m.fuente?.url ?? '') || !/^\d{4}-\d{2}-\d{2}$/.test(m.fuente?.fechaVerificacion ?? '')) {
    errores.push('La fuente debe tener cita, enlace https y fecha de verificación (AAAA-MM-DD).');
  }
  if (!Array.isArray(m.cursos) || !m.cursos.length || m.cursos.some((c) => !c.nombre)) errores.push('Faltan cursos transcritos de la fuente.');
  return errores;
}

/** Malla verificada de una carrera, o null si no existe (nunca se completa con datos inventados). */
export function mallaDe(carreraId, mallas = MALLAS) {
  const m = mallas.find((x) => x.carreraId === carreraId);
  return m && validarMalla(m).length === 0 ? m : null;
}
